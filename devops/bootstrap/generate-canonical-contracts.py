#!/usr/bin/env python3
"""Regenerate the Defs canonical model contracts through the legacy Defs Codegen.

The established Defs Codegen remains the bootstrap compiler of interface contracts:
no file in ``java.gen`` or ``python.gen`` may be modified manually. This
isolated run deliberately owns only the canonical-model file set, leaving
existing generated contracts untouched. ``--check`` verifies reproducibility.

Invoke in a source checkout with ``--source-dependencies`` or in a Modustro
build environment with the published Python libraries installed.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shutil
import sys
from tempfile import TemporaryDirectory


def _source_dependencies(root: Path) -> None:
    """Add only explicit local source dependency roots for an offline build."""
    sibling = root.parent / 'pub.lib.General'
    if not sibling.is_dir():
        raise SystemExit('Missing sibling pub.lib.General for --source-dependencies')
    for repo in (root, sibling):
        for branch in ('python', 'python.gen', 'config'):
            for directory in repo.rglob('src/product/' + branch):
                if directory.is_dir():
                    sys.path.insert(0, str(directory.resolve()))


def _manifest() -> dict:
    """Return the explicit Algites cross-language native codegen settings."""
    return {
        'artifact': 'generators/code/defscodegen/intf',
        'schema_inputs': [{'kind': 'jsondefs',
                           'directory': 'generators/code/defscodegen/intf/src/product/jsondefs'}],
        'schema_input_naming_conventions': {'jsondefs': 'algites-jsondef-schema-versioned_1'},
        'technology_outputs': {
            language: f'generators/code/defscodegen/intf/src/product/{language}.gen'
            for language in ('java', 'python')},
        'technology_output_naming_conventions': {
            language: {'jsondefs': f'algites-{language}-gen-intf-versioned_1'}
            for language in ('java', 'python')},
        'common_codegen_naming_conventions': {
            language: f'algites-{language}-codegen-common_1'
            for language in ('java', 'python')},
        'defs_codegen_naming_conventions': {
            language: f'algites-{language}-defscodegen-standard_1'
            for language in ('java', 'python')},
        'naming_convention_files': ['resource:standard-conventions.yml',
            'resource:algites-java-name-conventions.yml',
            'resource:algites-python-name-conventions.yml',
            'resource:algites-jsondef-name-conventions.yml',
            'resource:algites-java-common-codegen-conventions.yml',
            'resource:algites-python-common-codegen-conventions.yml',
            'resource:algites-java-defs-codegen-conventions.yml',
            'resource:algites-python-defs-codegen-conventions.yml'],
        'languages': ['java', 'python'],
    }


def main() -> int:
    """Produce or verify the generated contract sources, preserving other artifacts."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify generated bytes without changing sources')
    parser.add_argument('--source-dependencies', action='store_true',
                        help='Use sibling pub.lib.General and current tool sources instead of installed packages')
    opts = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    if opts.source_dependencies:
        _source_dependencies(root)
    from eu.algites.tool.codegen.defs.old.impl.standard.aic_schema_contract_bindings_generator import (
        AIcSchemaContractBindingsGenerator)
    source = (root / 'generators/code/defscodegen/intf/src/product/jsondefs/eu/algites/tool/codegen/defs/model'
              / 'canonical-model_1.jsondef.schema.json')
    if not source.is_file():
        raise SystemExit('Canonical model schema is missing: ' + str(source))
    state = root / 'generators/code/defscodegen/intf/generated-canonical-contracts.json'
    previous = json.loads(state.read_text()) if state.is_file() else []
    with TemporaryDirectory(prefix='algites-canonical-codegen-') as directory:
        temp = Path(directory)
        relative = source.relative_to(root)
        staged = temp / relative
        staged.parent.mkdir(parents=True)
        staged.write_bytes(source.read_bytes())
        AIcSchemaContractBindingsGenerator().generate_manifest(temp, _manifest())
        generated_state = temp / 'build/run/schema-contract-bindings/generated-files.json'
        current = sorted(json.loads(generated_state.read_text(encoding='utf-8')))
        failures = []
        for name in current:
            if not name.startswith('generators/code/defscodegen/intf/src/product/') or not name.endswith(('.java', '.py')):
                raise ValueError('Generator emitted an unexpected path: ' + name)
            generated = temp / name
            destination = root / name
            if opts.check:
                if not destination.is_file() or destination.read_bytes() != generated.read_bytes():
                    failures.append(name)
            else:
                destination.parent.mkdir(parents=True, exist_ok=True)
                if not destination.is_file() or destination.read_bytes() != generated.read_bytes():
                    shutil.copyfile(generated, destination)
        previous_set, current_set = set(previous), set(current)
        if opts.check:
            if previous_set != current_set:
                failures.append('generated-canonical-contracts.json ownership manifest')
            if failures:
                print('Canonical generated contracts are stale or missing:\n' + '\n'.join(failures), file=sys.stderr)
                return 1
        else:
            for name in sorted(previous_set - current_set):
                target = root / name
                if target.is_file():
                    target.unlink()
            state.write_text(json.dumps(current, indent=2) + '\n')
        counts = {language: sum('/' + language + '.gen/' in name for name in current)
                  for language in ('java', 'python')}
        print('Canonical Defs contracts ' + ('checked' if opts.check else 'generated') + ': ' +
              ', '.join(f'{language}={count}' for language, count in counts.items()))
        return 0


if __name__ == '__main__':
    sys.exit(main())
