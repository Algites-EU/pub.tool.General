#!/usr/bin/env python3
"""Promote generated canonical bootstrap contracts to persistent *.extgen roots.

The output is source-generated (and committed), never edited by hand. During the
initial compiler bootstrap it is independent of the disposable *.gen roots.
The temporary pub.tool.General bootstrap invokes --refresh automatically after a
successful complete build; --prune-seed removes historical extra paths without
checking old hashes at the start.
--refresh-defs updates only read-only contracts while preserving the independent
SDO seed, to break a bootstrap cycle. --check validates schema provenance,
source roles and hashes without requiring disposable generated sources.
"""
from __future__ import annotations

import argparse
import os
import uuid
import hashlib
from pathlib import Path
import re
import shutil

from importlib.machinery import SourceFileLoader

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'generators/code/defscodegen/intf/src/product'
IMPLEMENTATION = ROOT / 'generators/code/defscodegen/impl/src/product'
# The interim bootstrap generates read-only Defs contracts AND independent SDO
# writable contracts into the selected input artifact's *.gen tree. For the
# canonical model, that artifact is defscodegen/intf (see sdo-java.gradle and
# generate_sources.py). The bootstrap ABI snapshot remains split between the
# historical interface/implementation extgen roots. Do not read the impl/*.gen
# tree: it is not the SDO CLI output and is empty after a clean bootstrap.
# Each tuple is (language, freshly generated input, persistent ABI destination).
OUTPUTS = (
    ('java', SOURCE / 'java.gen', SOURCE / 'java.extgen'),
    ('python', SOURCE / 'python.gen', SOURCE / 'python.extgen'),
    ('java', SOURCE / 'java.gen', IMPLEMENTATION / 'java.extgen'),
    ('python', SOURCE / 'python.gen', IMPLEMENTATION / 'python.extgen'),
)
OLD_PACKAGE = 'eu.algites.tool.codegen.defs.model'
NEW_PACKAGE = 'eu.algites.tool.codegen.defs.bootstrap.model'
OLD_PATH = Path(*OLD_PACKAGE.split('.'))
NEW_PATH = Path(*NEW_PACKAGE.split('.'))
SCHEMA = SOURCE / 'jsondefs/eu/algites/tool/codegen/defs/model/canonical-model_1.jsondef.schema.json'
NORMALIZE = SourceFileLoader('canonical_bootstrap_normalize', str(Path(__file__).with_name('normalize-canonical-bootstrap.py'))).load_module().normalize


def digest(data: bytes) -> str:
    """Return a stable content hash of generated bytes."""
    return hashlib.sha256(data).hexdigest()


def relocate(text: str, language: str) -> str:
    """Relocate import/package identifiers without changing canonical schema IDs."""
    if language == 'java':
        # Both read-only contracts and independent writable SDO output use the
        # same model package root, optionally followed by .impl(.intf).
        text, count = re.subn(r'(?m)^(package\s+)' + re.escape(OLD_PACKAGE)
                              + r'(?=\.impl(?:\.intf)?;|;)',
                              lambda m: m.group(1) + NEW_PACKAGE, text)
        if count != 1:
            raise ValueError('Expected exactly one Java package declaration')
        # Relocate imported/fully qualified Java type names as well, without
        # rewriting the canonical schema IDs embedded in annotation literals.
        text = re.sub(r'\b' + re.escape(OLD_PACKAGE)
                      + r'(?=\.(?:impl\.|[A-Z]))', NEW_PACKAGE, text)
    else:
        text = re.sub(r'(?m)^(\s*(?:from|import)\s+)' + re.escape(OLD_PACKAGE)
                      + r'(?=\.(?:[a-z_]|impl)|\s|$)',
                      lambda m: m.group(1) + NEW_PACKAGE, text)
        # CHOICE contracts store the generated variant module identities as
        # string literals for lazy imports, not Python import statements.
        # These must follow the relocated bootstrap namespace as well, while
        # the canonical schema IDs in annotation strings remain unchanged.
        text = re.sub(r'(?m)^([ \t]*__xml_choice_variant_imports__\s*=\s*)([^\n]*)$',
                      lambda m: m.group(1) + m.group(2).replace(
                          OLD_PACKAGE + '.', NEW_PACKAGE + '.'), text)
    return text


def collect_existing() -> dict[str, str]:
    """Record current *.extgen sources with repository-relative paths."""
    result = {}
    for _, _, root in OUTPUTS:
        for path in sorted(root.rglob('*')) if root.is_dir() else ():
            if path.is_file() and path.suffix in ('.py', '.java'):
                result[path.relative_to(ROOT).as_posix()] = digest(path.read_bytes())
    return result


def _generated_symbol(source: str, language: str) -> str | None:
    """Find the top-level generated Java/Python type declaration, if present."""
    if language == 'java':
        match = re.search(r'(?m)^public\s+(?:(?:sealed|non-sealed|abstract|final)\s+)*(?:interface|class|enum|record)\s+([A-Za-z_][A-Za-z_0-9]*)\b', source)
    else:
        match = re.search(r'(?m)^class\s+([A-Za-z_][A-Za-z_0-9]*)\b', source)
    return match.group(1) if match else None


def _source_content(name: str, content: dict[str, str] | None) -> str:
    """Return prospective staged text or the committed bootstrap source."""
    return content[name] if content is not None else (ROOT / name).read_text(encoding='utf-8')


def _generated_files(source_root: Path, language: str, mutable: bool) -> list[Path]:
    """Separate Defs and SDO outputs without inferring roles from naming profiles.

    Defs creates the read-only model under ``model``. The independent SDO CLI
    writes mutable interfaces/classes beneath ``model/impl`` in that SAME
    disposable tree. Each generated file belongs to exactly one destination.
    """
    base = source_root / OLD_PATH
    suffix = '.java' if language == 'java' else '.py'
    if not base.is_dir():
        return []
    result = []
    for item in sorted(base.rglob('*')):
        if not item.is_file() or item.suffix != suffix:
            continue
        is_mutable = item.relative_to(base).parts[0] == 'impl'
        if is_mutable == mutable:
            result.append(item)
    return result


def ensure_symmetry(files: dict[str, str],
                    content: dict[str, str] | None = None) -> dict[str, tuple[int, int]]:
    """Check that Java and Python ABI snapshots contain matching canonical types.

    Schema identity annotations are independently owned by XML/JSON/YAML and
    MUST NOT be compared across formats or demanded from writable SDO types.
    Check generated type identities and roles instead; helper enum/choice
    types may have no SDO counterpart.
    """
    counts: dict[str, tuple[int, int]] = {}
    symbols: dict[str, dict[str, set[str]]] = {}
    for language, suffix in (('java', '.java'), ('python', '.py')):
        read_root = 'generators/code/defscodegen/intf/src/product/' + language + '.extgen/'
        sdo_root = 'generators/code/defscodegen/impl/src/product/' + language + '.extgen/'
        read = [p for p in files if p.startswith(read_root) and p.endswith(suffix)]
        sdo = [p for p in files if p.startswith(sdo_root) and p.endswith(suffix)]
        if not read or not sdo:
            raise RuntimeError('Missing ' + language + ' Defs or SDO extgen sources')
        counts[language] = (len(read), len(sdo))
        roles: dict[str, set[str]] = {'read': set(), 'mutable': set(), 'concrete': set()}
        for role, paths in (('read', read), ('sdo', sdo)):
            for name in paths:
                symbol = _generated_symbol(_source_content(name, content), language)
                if not symbol:
                    raise RuntimeError('Cannot identify canonical generated type in ' + name)
                actual_role = (role if role == 'read' else
                               ('mutable' if '/impl/intf/' in name else 'concrete'))
                prefix = {'read': ('AIig', 'AIng'), 'mutable': ('AIigd',),
                          'concrete': ('AIcgd',)}[actual_role]
                if not symbol.startswith(prefix):
                    raise RuntimeError('Unexpected canonical ' + actual_role + ' type in ' + name + ': ' + symbol)
                if symbol in roles[actual_role]:
                    raise RuntimeError('Duplicate canonical ' + actual_role + ' type: ' + symbol)
                roles[actual_role].add(symbol)
        if len(roles['mutable']) != len(roles['concrete']):
            raise RuntimeError('Incomplete ' + language + ' canonical SDO pairs')
        if {('AIcgd' + sym[len('AIigd'):]) for sym in roles['mutable']} != roles['concrete']:
            raise RuntimeError('Mismatched ' + language + ' SDO interface/implementation types')
        for sym in roles['mutable']:
            if 'AIig' + sym[len('AIigd'):] not in roles['read']:
                raise RuntimeError('Missing read-only counterpart for canonical SDO ' + sym)
        symbols[language] = roles
    if counts['java'] != counts['python'] or symbols['java'] != symbols['python']:
        missing_python = {role: sorted(symbols['java'][role] - symbols['python'][role])
                          for role in symbols['java']}
        missing_java = {role: sorted(symbols['python'][role] - symbols['java'][role])
                        for role in symbols['java']}
        raise RuntimeError('Java/Python canonical bootstrap differs: '
                           + repr(counts) + '; missing_python=' + repr(missing_python)
                           + '; missing_java=' + repr(missing_java))
    return counts


def validate_read_roles(files: dict[str, str],
                        content: dict[str, str] | None = None) -> None:
    """Require new common DataObject metadata without comparing format identities.

    During the transition Defs may also emit deprecated format annotations;
    these are NOT evidence of separate logical contracts. The named type and
    its own schema-neutral metadata determine the common read-only API.
    """
    for language, suffix in (('java', '.java'), ('python', '.py')):
        prefix = ('generators/code/defscodegen/intf/src/product/'
                  + language + '.extgen/')
        for name in sorted(files):
            if not name.startswith(prefix) or not name.endswith(suffix):
                continue
            source = _source_content(name, content)
            symbol = _generated_symbol(source, language)
            if not symbol or not symbol.startswith('AIig'):
                continue  # Choice markers and enums may lack DataObject metadata.
            if language == 'java':
                if ('@eu.algites.lib.data.dataobject.AIaDataObject(' in source
                        and 'eu.algites.lib.data.dataobject.AIiDataObject' not in source):
                    raise RuntimeError('Invalid common Java DataObject base: ' + name)
            elif '__data_object__' in source:
                header = re.search(r'(?m)^class\s+' + re.escape(symbol) + r'\(([^\n]+)\)', source)
                if header and 'AIiDataObject' not in header.group(1):
                    raise RuntimeError('Invalid common Python DataObject base: ' + name)


def validate_sdo_roles(files: dict[str, str],
                       content: dict[str, str] | None = None) -> None:
    """Check every generated SDO pair against its matching read-only contract.

    Helper choice/union contracts are allowed to lack SDO counterparts; writable
    SDO interfaces themselves must never point to an absent read-only type.
    """
    for language, suffix in (('java', '.java'), ('python', '.py')):
        read_root = 'generators/code/defscodegen/intf/src/product/' + language + '.extgen/'
        sdo_root = 'generators/code/defscodegen/impl/src/product/' + language + '.extgen/'
        read = {_generated_symbol(_source_content(p, content), language): p
                for p in files if p.startswith(read_root) and p.endswith(suffix)}
        mutable = {_generated_symbol(_source_content(p, content), language): p
                   for p in files if p.startswith(sdo_root) and '/impl/intf/' in p and p.endswith(suffix)}
        concrete = {_generated_symbol(_source_content(p, content), language): p
                    for p in files if p.startswith(sdo_root) and '/impl/intf/' not in p and p.endswith(suffix)}
        for symbol, path in mutable.items():
            read_symbol = 'AIig' + symbol[len('AIigd'):]
            concrete_symbol = 'AIcgd' + symbol[len('AIigd'):]
            if read_symbol not in read or concrete_symbol not in concrete:
                raise RuntimeError('Incomplete canonical SDO hierarchy: ' + str(path))
            source = _source_content(path, content)
            implementation = _source_content(concrete[concrete_symbol], content)
            # Both technologies use generated typed accessors/interfaces;
            # annotations are not required to be repeated on SDO descendants.
            if read_symbol not in source:
                raise RuntimeError('SDO interface does not extend read-only type: ' + path)
            if symbol not in implementation:
                raise RuntimeError('SDO implementation does not implement interface: ' + concrete[concrete_symbol])


def refresh_defs() -> None:
    """Promote Defs-only sources; keep the independently generated SDO seed.

    This is the explicit recovery operation when the committed first-stage Defs
    snapshot was generated using the wrong input naming role. It never rewrites
    an SDO source or changes the ordinary bootstrap/prepare operation.
    """
    if not SCHEMA.is_file():
        raise FileNotFoundError(SCHEMA)
    current = collect_existing()
    read: dict[str, str] = {}
    for language, source_root, output in OUTPUTS[:2]:
        source = source_root / OLD_PATH
        suffix = '.java' if language == 'java' else '.py'
        files = _generated_files(source_root, language, mutable=False)
        if not files:
            raise RuntimeError('Missing generated ' + language + ' Defs contracts: ' + str(source))
        for file in files:
            target = output / NEW_PATH / file.relative_to(source)
            relative = target.relative_to(ROOT).as_posix()
            read[relative] = relocate(NORMALIZE(file.read_text(encoding='utf-8'), language), language)
    # Build a complete prospective snapshot including the unchanged SDO seeds.
    output_roots = [out.relative_to(ROOT).as_posix() + '/' for _, _, out in OUTPUTS[:2]]
    seed = {name: (ROOT / name).read_text(encoding='utf-8') for name in current
            if not any(name.startswith(root) for root in output_roots)}
    if not seed:
        raise RuntimeError('Missing independent SDO bootstrap seed; cannot refresh Defs alone')
    result = {name: digest(text.encode('utf-8')) for name, text in {**seed, **read}.items()}
    validate_read_roles(result, {**seed, **read})
    counts = ensure_symmetry(result, {**seed, **read})
    validate_sdo_roles(result, {**seed, **read})
    # All validation precedes the staged replacement. The SDO trees remain
    # untouched: Defs and SDO are independent generators.
    _publish(read, OUTPUTS[:2])
    _discard_legacy_sidecar()
    print(f'Promoted read-only bootstrap contracts, retained independent SDO seed: '
          f'{len(result)} files (Java={sum(counts["java"])}, '
          f'Python={sum(counts["python"])}; '
          f'read={counts["java"][0]}, SDO={counts["java"][1]} per language)')


def _discard_legacy_sidecar() -> None:
    """Discard the retired bootstrap hash list after successful validation.

    This path is never read or generated; older checkouts may still contain it.
    """
    old = ROOT / 'generators/code/defscodegen/intf/canonical-bootstrap-extgen.json'
    if old.is_file() or old.is_symlink():
        old.unlink()


def check() -> None:
    """Validate the source snapshot itself, without persisted provenance files.

    A seed is needed before newly generated ``*.gen`` files exist, so the
    contract/API structure is checked directly. A full ``--refresh`` checks
    fresh outputs of both independent codegens before replacing these trees.
    """
    if not SCHEMA.is_file():
        raise FileNotFoundError(SCHEMA)
    files = collect_existing()
    validate_read_roles(files)
    counts = ensure_symmetry(files)
    validate_sdo_roles(files)
    print(f'Canonical bootstrap *.extgen verified from source contents: {len(files)} files '
          f'(Java={sum(counts["java"])}, Python={sum(counts["python"])}; '
          f'read={counts["java"][0]}, SDO={counts["java"][1]} per technology)')


def prune_seed() -> None:
    """Validate the existing compiler seed without guessing its file list.

    A source-only initial bootstrap cannot derive a trustworthy expected file
    list before running Defs/SDO. Do not delete arbitrary sources based on a
    previously persisted manifest. A successful ``--refresh`` replaces all
    four source trees entirely and thereby removes obsolete paths safely.
    """
    files = collect_existing()
    if not files:
        raise RuntimeError('No generated canonical compiler ABI snapshot found')
    clean: dict[str, str] = {}
    for name in files:
        language = 'java' if name.endswith('.java') else 'python'
        content = (ROOT / name).read_text(encoding='utf-8')
        symbol = _generated_symbol(content, language)
        # Generated canonical class names start immediately with the semantic
        # type. Historical per-format projections used an extra separator and
        # are never a valid compiler ABI contract.
        if symbol is None or not re.match(r'^(?:AIig|AIigd|AIcgd|AIng)[A-Z]', symbol):
            continue
        # Existing source-generated ABI snapshots may precede the rename of
        # the shared SmartDataObject implementation module. Keep the ABI seed
        # usable without reviving an old format-specific runtime.
        content = NORMALIZE(content, language)
        content = content.replace('eu.algites.lib.data.smartdataobject.impl.standard.',
                                  'eu.algites.lib.data.smartdataobject.impl.common.')
        clean[name] = content
    hashes = {name: digest(content.encode('utf-8')) for name, content in clean.items()}
    validate_read_roles(hashes, clean)
    counts = ensure_symmetry(hashes, clean)
    validate_sdo_roles(hashes, clean)
    if len(clean) != len(files) or any(clean[name] != (ROOT / name).read_text(encoding='utf-8') for name in clean):
        _publish(clean, OUTPUTS)
    _discard_legacy_sidecar()
    print(f'Unified canonical compiler ABI seed validated: {len(clean)} files; '
          f'read={counts["java"][0]}, SDO={counts["java"][1]} per technology')


def _publish(sources: dict[str, str],
             outputs: tuple[tuple[str, Path, Path], ...]) -> None:
    """Replace selected source trees with rollback and no metadata sidecar.

    All validation has completed before entry. Staging remains on the same
    filesystem; temporary directories are cleaned even on a failed rename.
    """
    token = uuid.uuid4().hex
    staged: list[tuple[Path, Path, Path]] = []
    committed: list[tuple[Path, Path, bool]] = []
    succeeded = False
    try:
        for _, _, output in outputs:
            if output.is_symlink():
                raise RuntimeError('Refusing symlinked bootstrap destination: ' + str(output))
            output.parent.mkdir(parents=True, exist_ok=True)
            stage = output.with_name(output.name + '.stage-' + token)
            backup = output.with_name(output.name + '.backup-' + token)
            stage.mkdir(mode=0o700)
            staged.append((output, stage, backup))
        roots = {output.relative_to(ROOT).as_posix() + '/': stage
                 for output, stage, _ in staged}
        for name, value in sorted(sources.items()):
            prefix = next((prefix for prefix in roots if name.startswith(prefix)), None)
            if prefix is None:
                raise RuntimeError('Unowned bootstrap output: ' + name)
            target = roots[prefix] / name[len(prefix):]
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(value, encoding='utf-8')
        for output, stage, backup in staged:
            existed = output.exists()
            if existed:
                os.replace(output, backup)
            try:
                os.replace(stage, output)
            except BaseException:
                if existed:
                    os.replace(backup, output)
                raise
            committed.append((output, backup, existed))
        succeeded = True
    except BaseException:
        for output, backup, existed in reversed(committed):
            if output.exists():
                shutil.rmtree(output)
            if existed:
                os.replace(backup, output)
        raise
    finally:
        for _, stage, backup in staged:
            if stage.exists():
                shutil.rmtree(stage)
            if succeeded and backup.exists():
                shutil.rmtree(backup)


def refresh() -> None:
    """Atomically promote the four freshly generated Defs/SDO source sets.

    Validate complete newly generated Defs/SDO source contents first, then
    exchange all four trees with rollback and without persistent metadata.
    A failure must not leave half the bootstrap model refreshed. Each stage
    uses the same parent filesystem as its destination for safe renames.
    """
    if not SCHEMA.is_file():
        raise FileNotFoundError(SCHEMA)
    sources: dict[str, str] = {}
    for index, (language, source_root, output) in enumerate(OUTPUTS):
        source = source_root / OLD_PATH
        mutable = index >= 2
        files = _generated_files(source_root, language, mutable=mutable)
        if not files:
            role = 'SDO' if mutable else 'Defs'
            raise RuntimeError('Missing freshly generated canonical ' + language
                               + ' ' + role + ' contracts in ' + str(source)
                               + ('/impl' if mutable else ''))
        if output.is_symlink():
            raise RuntimeError('Refusing symlinked bootstrap destination: ' + str(output))
        for file in files:
            if file.is_symlink():
                raise RuntimeError('Refusing symlinked generated canonical source: ' + str(file))
            target = output / NEW_PATH / file.relative_to(source)
            relative = target.relative_to(ROOT).as_posix()
            if relative in sources:
                raise RuntimeError('Duplicate generated canonical source: ' + relative)
            sources[relative] = relocate(NORMALIZE(file.read_text(encoding='utf-8'), language), language)
    result = {name: digest(value.encode('utf-8')) for name, value in sources.items()}
    validate_read_roles(result, sources)
    counts = ensure_symmetry(result, sources)
    validate_sdo_roles(result, sources)

    _publish(sources, OUTPUTS)
    _discard_legacy_sidecar()
    print(f'Promoted {len(result)} generated contracts into persistent *.extgen roots '
          f'(Java={sum(counts["java"])}, Python={sum(counts["python"])}; '
          f'read={counts["java"][0]}, SDO={counts["java"][1]} per technology)')

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--refresh', action='store_true', help='Regenerate persistent snapshot from *.gen outputs')
    group.add_argument('--refresh-defs', action='store_true',
                       help='Update only read contracts, keeping existing generated SDO seed')
    group.add_argument('--check', action='store_true', help='Explicit check of committed snapshot')
    group.add_argument('--prune-seed', action='store_true', help='Validate first-stage compiler seed; obsolete files are replaced by --refresh')
    args = parser.parse_args()
    if args.refresh:
        refresh()
    elif args.refresh_defs:
        refresh_defs()
    elif args.prune_seed:
        prune_seed()
    else:
        check()


if __name__ == '__main__':
    main()
