"""Canonical graph operations over *schema-generated* DataObject and SDO types.

This module owns no canonical data classes. All node instances are concrete SDO
implementations generated by the independent SDO Codegen from Defs' generated
read-only ``AIig*`` schema contracts. The conveniences below support constructing
and normalizing the graph; the schema remains its sole definition.

The temporary Python property/constructor bridge allows the native frontend,
linker and emitters to migrate without reintroducing a parallel DTO hierarchy.
"""
