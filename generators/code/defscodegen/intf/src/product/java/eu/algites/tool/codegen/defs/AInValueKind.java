package eu.algites.tool.codegen.defs;

/** Normalized property value kinds. */
public enum AInValueKind {
    /** Represents the string value. */
    STRING,
    /** Represents the integer value. */
    INTEGER,
    /** Represents the number value. */
    NUMBER,
    /** Represents the boolean value. */
    BOOLEAN,
    /** Represents the array value. */
    ARRAY,
    /** Represents the object value. */
    OBJECT,
    /** Represents the reference value. */
    REFERENCE,
    /** Represents the any value. */
    ANY
}
